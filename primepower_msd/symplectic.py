"""Shared symplectic primitives for ring-qudit (Z_d, d = 2^k) stabilizer codes.

Consolidates what the Phase 1-5 work kept in untracked scripts (`gr_kd.py`, `scratchpad/logical.py`,
`scratchpad/n12run.py`, `scratchpad/p2_engine.py`) into one package module, parametric in d:

  * rows `(a | b)` of length 2n over Z_d; symplectic form <u,v> = a.b' - a'.b  (mod d);
  * `SpanTester` (cached Howell form) for fast module membership;
  * centralizer generators, k (log_d of |C|/|S| over 2), brute symplectic distance (reference only);
  * `logical_symplectic_basis`: hyperbolic logical pairs with a UNIT (odd) pairing -> the genuine
    order-d logical axes; even-only directions are reported as "soft" (the dense-validated routine
    from scratchpad/logical.py, unchanged in logic);
  * `Z4Code`: a code object with the cached derived data the hosting / distance / search modules need
    (X-generators, pure-Z stabilizers, support module, logical axes, k).

Nothing here enumerates d^n objects; everything goes through Howell forms.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from itertools import combinations, product
from functools import cached_property

import numpy as np

from .ringlinalg import howell_form, in_span, module_size, right_kernel_howell


# --------------------------------------------------------------------------- basic symplectic algebra
def symp(u, v, n: int, d: int = 4) -> int:
    """<(a|b),(a'|b')> = a.b' - a'.b  (mod d)."""
    u = np.asarray(u, dtype=np.int64); v = np.asarray(v, dtype=np.int64)
    return int((np.dot(u[:n], v[n:]) - np.dot(v[:n], u[n:])) % d)


def is_isotropic(rows, n: int, d: int = 4) -> bool:
    R = [np.asarray(r, dtype=np.int64) for r in rows]
    return all(symp(R[i], R[j], n, d) == 0 for i in range(len(R)) for j in range(i, len(R)))


class SpanTester:
    """Fast repeated membership tests in the Z_d-module generated by `gens` (Howell form cached)."""

    def __init__(self, gens, n_mod: int):
        self.n = n_mod
        G = np.atleast_2d(np.asarray(gens, dtype=np.int64)) if len(gens) else np.zeros((0, 0), int)
        self.H = howell_form(G, n_mod) if G.size else np.zeros((0, 0), dtype=int)
        self.piv = []
        for row in self.H:
            cols = np.nonzero(np.asarray(row) % n_mod)[0]
            self.piv.append(int(cols[0]) if len(cols) else -1)

    def contains(self, v) -> bool:
        n = self.n
        w = [int(x) % n for x in v]
        ncols = len(w)
        for row, pc in zip(self.H, self.piv):
            if pc < 0:
                continue
            g = int(row[pc]) % n
            if w[pc] % g != 0:
                return False
            q = (w[pc] % n) // g
            if q:
                w = [(w[j] - q * int(row[j])) % n for j in range(ncols)]
        return all(x % n == 0 for x in w)


def centralizer_gens(stab_rows, n: int, d: int = 4) -> list[list[int]]:
    """Generators of C(S) = {v : <v,g> = 0 for all g in S}: v.(gb | -ga) = 0 -> right kernel."""
    M = []
    for g in stab_rows:
        g = np.asarray(g, dtype=np.int64) % d
        M.append(np.concatenate([g[n:], (-g[:n]) % d]) % d)
    if not M:
        return [list(r) for r in np.eye(2 * n, dtype=int)]
    return [list(map(int, r)) for r in right_kernel_howell(np.array(M, dtype=np.int64), d)]


def compute_k(stab_rows, n: int, d: int = 4) -> tuple[float, int, int]:
    """(k, |C|, |S|) with |C|/|S| = d^{2k}.  k may be a half-integer for non-free quotients."""
    cg = centralizer_gens(stab_rows, n, d)
    C = module_size(cg, d) if cg else 1
    S = module_size(stab_rows, d) if len(stab_rows) else 1
    ratio = C // S
    twok = math.log(ratio, d) if ratio > 1 else 0.0
    return round(twok, 6) / 2, C, S


def symplectic_weight(v, n: int, d: int = 4) -> int:
    v = np.asarray(v, dtype=np.int64) % d
    return int(np.count_nonzero((v[:n] != 0) | (v[n:] != 0)))


def brute_distance(stab_rows, n: int, d: int = 4, cap: int = 4) -> int:
    """Min symplectic weight in C(S) \\ S by brute enumeration of weight-w vectors (reference only;
    fine for d=3 at n<=12).  Returns cap+1 when no logical of weight <= cap exists."""
    st = SpanTester(stab_rows, d)
    rows = [np.asarray(r, dtype=np.int64) % d for r in stab_rows]
    nz = [t for t in product(range(d), repeat=2) if t != (0, 0)]
    for w in range(1, cap + 1):
        for pos in combinations(range(n), w):
            for vals in product(nz, repeat=w):
                v = np.zeros(2 * n, dtype=np.int64)
                for p, (ai, bi) in zip(pos, vals):
                    v[p] = ai; v[n + p] = bi
                if all(symp(v, g, n, d) == 0 for g in rows) and not st.contains(v):
                    return w
    return cap + 1


# --------------------------------------------------------------------------- logical basis
def _reduce_pool(pool, tester: "SpanTester", d):
    return [c for c in pool if any(t % d for t in c) and not tester.contains(c)]


def logical_pairs(stab_rows, n: int, d: int = 4) -> tuple[list[tuple[list[int], list[int]]], int]:
    """Hyperbolic logical pairs (g, h) over Z_d with <g,h> = 1 (g = logical X, h = logical Z) and the
    number of 'soft' directions (centralizer elements pairing evenly with everything left).

    Same procedure as scratchpad/logical.py (dense-validated): greedy symplectic Gram-Schmidt on the
    centralizer-mod-stabilizer pool, pairing on a UNIT (odd) form only.  Membership tests use a cached
    Howell form (SpanTester) that is rebuilt only when the span grows.
    """
    rows = [list(map(int, np.asarray(r, dtype=np.int64) % d)) for r in stab_rows]
    cg = centralizer_gens(rows, n, d)
    span = [list(r) for r in rows] if rows else []
    tester = SpanTester(span, d) if span else SpanTester(np.zeros((1, 2 * n), dtype=np.int64), d)
    pool = _reduce_pool([list(v) for v in cg], tester, d)
    pairs = []; soft = 0
    while pool:
        g = pool[0]
        h = None; sval = 0
        for cand in pool[1:]:
            s = symp(g, cand, n, d)
            if s % 2 == 1:
                h = cand; sval = s; break
        if h is None:
            soft += 1
            span = span + [g]
            tester = SpanTester(span, d)
            pool = _reduce_pool(pool[1:], tester, d)
            continue
        inv = pow(sval, -1, d)
        h = [(inv * t) % d for t in h]
        pairs.append((g, h))
        span = span + [g, h]
        tester = SpanTester(span, d)
        newpool = []
        for c in pool:
            if c is g or c is h:
                continue
            ch = symp(c, h, n, d); cgp = symp(c, g, n, d)
            newpool.append([(c[i] - ch * g[i] + cgp * h[i]) % d for i in range(2 * n)])
        pool = _reduce_pool(newpool, tester, d)
    return pairs, soft


def logical_symplectic_basis(stab_rows, n: int, d: int = 4):
    """(Xaxes, k_genuine, soft): Xaxes = X-parts of the genuine logical-X representatives."""
    pairs, soft = logical_pairs(stab_rows, n, d)
    return [g[:n] for (g, h) in pairs], len(pairs), soft


# --------------------------------------------------------------------------- the code object
@dataclass
class Z4Code:
    """A Z_d stabilizer code given by symplectic generator rows (a|b), shape (r, 2n).  d defaults to 4."""

    n: int
    rows: np.ndarray
    d: int = 4
    label: str = ""

    def __post_init__(self):
        self.rows = (np.atleast_2d(np.asarray(self.rows, dtype=np.int64)) % self.d).astype(np.int64)
        if self.rows.size == 0:
            self.rows = np.zeros((0, 2 * self.n), dtype=np.int64)
        assert self.rows.shape[1] == 2 * self.n, "rows must have length 2n"

    # ---- constructors
    @classmethod
    def from_symplectic(cls, rows, n: int, d: int = 4, label: str = ""):
        return cls(n, np.asarray(rows), d, label)

    @classmethod
    def from_css(cls, MX, MZ, n: int, d: int = 4, label: str = ""):
        MX = np.atleast_2d(np.asarray(MX, dtype=np.int64)) % d if len(MX) else np.zeros((0, n), int)
        MZ = np.atleast_2d(np.asarray(MZ, dtype=np.int64)) % d if len(MZ) else np.zeros((0, n), int)
        if MX.size and MZ.size:
            assert np.all((MX @ MZ.T) % d == 0), "CSS blocks must commute: MX . MZ^T = 0 mod d"
        rows = []
        for a in MX:
            rows.append(np.concatenate([a, np.zeros(n, int)]))
        for b in MZ:
            rows.append(np.concatenate([np.zeros(n, int), b]))
        return cls(n, np.array(rows, dtype=np.int64).reshape(-1, 2 * n), d, label)

    @classmethod
    def load(cls, path, d: int = 4, label: str = ""):
        W = np.array(np.load(path, allow_pickle=True), dtype=np.int64) % d
        return cls(W.shape[1] // 2, W, d, label or str(path))

    # ---- derived data (cached)
    @cached_property
    def is_css(self) -> bool:
        return all((not np.any(r[:self.n])) or (not np.any(r[self.n:])) for r in self.rows)

    @cached_property
    def isotropic(self) -> bool:
        return is_isotropic(self.rows, self.n, self.d)

    @cached_property
    def x_gens(self) -> list[list[int]]:
        """X-parts of rows with nonzero X-part: generators of proj_X(S) (= M_X for CSS)."""
        return [list(map(int, r[:self.n])) for r in self.rows if np.any(r[:self.n])]

    @cached_property
    def z_rows(self) -> list[list[int]]:
        """Z-parts of the pure-Z generator rows (CSS: M_Z generators)."""
        return [list(map(int, r[self.n:])) for r in self.rows if not np.any(r[:self.n])]

    @cached_property
    def pure_z_gens(self) -> list[list[int]]:
        """Generators of the pure-Z sub-stabilizer {(0|b) in S}: combos c with c.Gx = 0 give c.Gz
        (scratchpad/n12run.pureZ_gens, kernel via Howell instead of brute)."""
        n, d = self.n, self.d
        if self.rows.shape[0] == 0:
            return []
        Gx = self.rows[:, :n]; Gz = self.rows[:, n:]
        if not np.any(Gx):
            return [list(map(int, b)) for b in Gz if np.any(b)]
        combos = right_kernel_howell(Gx.T % d, d)       # c with Gx^T c = 0  <=> c @ Gx = 0
        out = []
        for c in combos:
            b = (np.asarray(c, dtype=np.int64) @ Gz) % d
            if np.any(b):
                out.append(list(map(int, b)))
        # include explicit pure-Z rows (they are in the kernel too, but be safe) and canonicalize
        out += self.z_rows
        H = howell_form(np.array(out, dtype=np.int64), d) if out else np.zeros((0, n), int)
        return [list(map(int, r)) for r in H if np.any(np.asarray(r) % d)]

    @cached_property
    def support_gens(self) -> list[list[int]]:
        """Generators of supp(C) = {x : x.b = 0 for all pure-Z stabilizers b} (full space if none)."""
        n, d = self.n, self.d
        if not self.pure_z_gens:
            return [list(r) for r in np.eye(n, dtype=int)]
        return [list(map(int, r)) for r in right_kernel_howell(np.array(self.pure_z_gens, dtype=np.int64), d)]

    @cached_property
    def support_size(self) -> int:
        return module_size(self.support_gens, self.d) if self.support_gens else 1

    @cached_property
    def logical(self):
        """(Xaxes, k_genuine, soft)."""
        return logical_symplectic_basis(self.rows, self.n, self.d)

    @property
    def logical_axes(self) -> list[list[int]]:
        return self.logical[0]

    @property
    def k_genuine(self) -> int:
        return self.logical[1]

    @property
    def soft(self) -> int:
        return self.logical[2]

    @cached_property
    def k_info(self) -> tuple[float, int, int]:
        return compute_k(self.rows, self.n, self.d)

    @property
    def k(self) -> float:
        return self.k_info[0]

    @cached_property
    def free_quotient_ok(self) -> bool:
        """True iff the logical-X axes extend proj_X(S) freely: |<M_X, axes>| = |M_X| d^k_genuine.
        When this holds (and soft == 0) the coset-rep hosting test is exact."""
        d = self.d
        base = self.x_gens
        sz0 = module_size(base, d) if base else 1
        ext = base + self.logical_axes
        sz1 = module_size(ext, d) if ext else 1
        return sz1 == sz0 * d ** len(self.logical_axes)

    def stabilizer_tester(self) -> SpanTester:
        return SpanTester(self.rows, self.d)

    def gamma(self, distance: int) -> float | None:
        k = self.k
        if k <= 0 or distance <= 1:
            return None
        return math.log(self.n / k) / math.log(distance)

    def __repr__(self):
        return f"Z4Code(n={self.n}, r={self.rows.shape[0]}, d={self.d}{', ' + self.label if self.label else ''})"


def blocks(code: Z4Code, m: int) -> Z4Code:
    """m disjoint copies of `code` on m*n qudits (block b occupies qudits [b*n, (b+1)*n))."""
    n, d = code.n, code.d
    rows = []
    for b in range(m):
        for r in code.rows:
            a = np.zeros(m * n, dtype=np.int64); z = np.zeros(m * n, dtype=np.int64)
            a[b * n:(b + 1) * n] = r[:n]; z[b * n:(b + 1) * n] = r[n:]
            rows.append(np.concatenate([a, z]))
    return Z4Code(m * n, np.array(rows, dtype=np.int64).reshape(-1, 2 * m * n), d,
                  label=f"{m}x[{code.label}]" if code.label else f"{m} blocks")
